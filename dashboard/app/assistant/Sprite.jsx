export const VISAGES = Object.keys(SPRITES);
export const VISAGE_DEFAUT = 'corbeau';

export default function Sprite({ nom }) {
  const grille = SPRITES[nom] || SPRITES[VISAGE_DEFAUT];
  const pixels = [];
  grille.forEach((ligne, y) => [...ligne].forEach((c, x) => {
    if (c !== '.') pixels.push(<rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" fill="currentColor" opacity={c === '+' ? 0.5 : 1} />);
  }));
  return (
    <svg viewBox="0 0 16 16" className="sprite" shapeRendering="crispEdges" aria-hidden="true">
      <rect width="16" height="16" fill="#14120e" />
      {pixels}
      <rect x="0.25" y="0.25" width="15.5" height="15.5" fill="none" stroke="currentColor" strokeWidth="0.5" opacity="0.8" />
    </svg>
  );
}
